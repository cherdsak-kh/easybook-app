/**
 * Sized by `.notif-glyph` (18px, inside the bell's 36px tile) or, with `size="lg"`, by
 * `.notif-glyph-lg` (20px, inside the page's 40px tile). Always decorative.
 *
 * `name` is a plain string on purpose: it arrives from the wire, and `Object.hasOwn` is what keeps a
 * name like `toString` from reaching into the prototype chain for a "path".
 */
export function NotifGlyph({
  name,
  size = 'md',
}: {
  name: string
  size?: 'md' | 'lg'
}): ReactElement {
  const d = Object.hasOwn(NOTIF_GLYPHS, name)
    ? NOTIF_GLYPHS[name as NotificationIcon]
    : FALLBACK_GLYPH
  return (
    <svg
      aria-hidden="true"
      className={size === 'lg' ? 'notif-glyph notif-glyph-lg' : 'notif-glyph'}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      viewBox="0 0 24 24"
    >
      <path strokeLinecap="round" strokeLinejoin="round" d={d} />
    </svg>
  )
}
